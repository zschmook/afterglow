const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
let timer,cycles=0,releases=0;const keys=[],messages=[];
const core={tick:()=>cycles++,key:(...k)=>keys.push(k),release:()=>releases++,frame:()=>new Uint8Array(16000),on:()=>true};
const context={Uint8Array,importScripts:()=>{},AfterglowTI89:{create:()=>core},postMessage:m=>messages.push(m),setInterval:f=>{timer=f;}};
vm.createContext(context);vm.runInContext(fs.readFileSync('assets/ti89-worker.js','utf8'),context);
const send=data=>context.onmessage({data});
send({type:'load',rom:new ArrayBuffer(0)});assert.equal(messages.at(-1).type,'loaded');
timer();assert.equal(cycles,0,'Hidden calculator must not execute');
send({type:'pause',paused:false});send({type:'keys',codes:[25]});
for(let i=0;i<150;i++)timer();assert.equal(keys.length,0,'Ignore input until boot completes');
assert.equal(messages.filter(m=>m.type==='ready').length,1);
for(const codes of [[49],[81],['1'],[],[1,2,3,4]])send({type:'keys',codes});
timer();assert.equal(keys.length,0,'Invalid matrix codes must be ignored');
send({type:'keys',codes:[7,43]});timer();assert.deepEqual(keys,[[7,true],[43,true]],'ALPHA chord presses both keys together');
send({type:'keys',codes:[25]});send({type:'pause',paused:true});assert.equal(releases,1);
const pausedCycles=cycles;for(let i=0;i<100;i++)timer();assert.equal(cycles,pausedCycles);
send({type:'pause',paused:false});for(let i=0;i<30;i++)timer();assert.equal(keys.length,2,'Resume must not replay queued input');
send({type:'keys',codes:[80]});for(let i=0;i<7;i++)timer();assert.deepEqual(keys.slice(-2),[[80,true],[80,false]]);
assert.ok(messages.some(m=>m.type==='frame'&&m.on&&m.pixels.length===16000));
send({type:'load'});assert.equal(messages.at(-1).type,'error','Reject a second core in the same worker');
console.log('TI-89 worker: boot gating, chords, invalid keys, hidden CPU, queue clearing and ON release passed.');
